static const char r3d_fs_main[] =
"#version 300 es\n"
"precision highp float;\n"
"precision highp sampler2DShadow;\n"
"in vec3 v_wp; in vec3 v_wn; flat in vec3 v_mn; in vec3 v_mp; in vec4 v_col; flat in float v_mat;\n"
"uniform vec3 u_cam;\n"
"uniform sampler2DShadow u_shadow; uniform mat4 u_lvp;\n"
"uniform float u_shadowOn; uniform float u_texel; uniform float u_soft; uniform float u_nbias; uniform float u_lrange;\n"
"uniform float u_rough; uniform float u_spec; uniform float u_emis; uniform float u_pixGrid; uniform float u_aoOn;\n"
"uniform vec3 u_ambS; uniform vec3 u_ambG;\n"
"uniform float u_plOn; uniform float u_plRad; uniform vec3 u_plPos; uniform vec3 u_plCol;\n"
"uniform float u_fog;\n"
"uniform vec3 u_skyZen; uniform vec3 u_skyHor; uniform vec3 u_skyGnd;\n"
"uniform vec3 u_L; uniform vec3 u_sunCol;\n"
"uniform float u_exposure; uniform float u_tm;\n"
"vec3 skyBase(vec3 d){\n"
"  float h = d.y;\n"
"  return h > 0.0 ? mix(u_skyHor, u_skyZen, pow(clamp(h, 0.0, 1.0), 0.5)) : mix(u_skyHor, u_skyGnd, pow(clamp(-h, 0.0, 1.0), 0.5));\n"
"}\n"
"vec3 skySun(vec3 d){\n"
"  float s = max(dot(d, u_L), 0.0);\n"
"  return u_sunCol * (pow(s, 1200.0) * 3.0 + pow(s, 28.0) * 0.10);\n"
"}\n"
"vec3 aces(vec3 x){ return clamp((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14), 0.0, 1.0); }\n"
"vec3 finish(vec3 c){\n"
"  c *= u_exposure;\n"
"  c = (u_tm > 0.5) ? aces(c) : clamp(c, 0.0, 1.0);\n"
"  return pow(c, vec3(1.0 / 2.2));\n"
"}\n"
"out vec4 o;\n"
"float shadowAt(vec3 wp, vec3 N, float ndl){\n"
"  if (u_shadowOn < 0.5) return 1.0;\n"
"  vec4 lp = u_lvp * vec4(wp + N * u_nbias, 1.0);\n"
"  vec3 sc = lp.xyz / lp.w * 0.5 + 0.5;\n"
"  if (sc.x < 0.0 || sc.x > 1.0 || sc.y < 0.0 || sc.y > 1.0 || sc.z > 1.0) return 1.0;\n"
"  float bias = (0.10 + 0.40 * (1.0 - ndl)) / u_lrange;\n"
"  float s = 0.0;\n"
"  for (int i = -1; i <= 1; i++) for (int j = -1; j <= 1; j++) {\n"
"    s += texture(u_shadow, vec3(sc.xy + vec2(float(i), float(j)) * u_texel * u_soft, sc.z - bias));\n"
"  }\n"
"  return s / 9.0;\n"
"}\n"
"void main(){\n"
"  vec3 N = normalize(v_wn);\n"
"  vec3 Vv = u_cam - v_wp; float dist = length(Vv); vec3 V = Vv / dist;\n"
"  if (dot(N, V) < 0.0) N = -N;\n"
"  int mat = int(v_mat + 0.5);\n"
"  vec3 alb = pow(v_col.rgb, vec3(2.2));\n"
"  float ao = (u_aoOn > 0.5) ? v_col.a : 1.0;\n"
"  float rough = u_rough; float specK = u_spec;\n"
"  if (mat == 0) { rough = mix(u_rough, 1.0, 0.55); specK = u_spec * 0.45; }\n"
"  else if (mat == 2) { rough = 0.6; specK = u_spec * 0.25; }\n"
"  else if (mat == 3) { rough = 0.85; specK = u_spec * 0.12; }\n"
"  if (mat <= 1 && abs(v_mn.z) > 0.5 && u_pixGrid > 0.0) {\n"
"    vec2 f = fract(v_mp.xy); vec2 e = min(f, 1.0 - f); float ed = min(e.x, e.y);\n"
"    float w = fwidth(v_mp.x) + fwidth(v_mp.y);\n"
"    float vis = 1.0 - smoothstep(0.30, 0.80, w);\n"
"    float g = smoothstep(0.0, 0.16, ed);\n"
"    alb *= mix(1.0, mix(1.0 - 0.5 * u_pixGrid, 1.0, g), vis);\n"
"  }\n"
"  if (mat == 3) {\n"
"    vec2 g = abs(fract(v_mp.xy / 32.0 - 0.5) - 0.5) / max(fwidth(v_mp.xy / 32.0), vec2(1e-4));\n"
"    float ln = 1.0 - min(min(g.x, g.y), 1.0);\n"
"    alb = mix(alb, alb * 2.2 + 0.01, ln * 0.35);\n"
"  }\n"
"  float ndl = max(dot(N, u_L), 0.0);\n"
"  float sh = (ndl > 0.0) ? shadowAt(v_wp, N, ndl) : 0.0;\n"
"  vec3 H = normalize(u_L + V);\n"
"  float ndh = max(dot(N, H), 0.0); float ndv = max(dot(N, V), 1e-3); float vdh = max(dot(V, H), 0.0);\n"
"  float a = rough * rough; float a2 = a * a;\n"
"  float dd = ndh * ndh * (a2 - 1.0) + 1.0;\n"
"  float D = a2 / (3.14159265 * dd * dd + 1e-6);\n"
"  float k = (rough + 1.0) * (rough + 1.0) / 8.0;\n"
"  float G = (ndl / (ndl * (1.0 - k) + k)) * (ndv / (ndv * (1.0 - k) + k));\n"
"  float F = 0.04 + 0.96 * pow(1.0 - vdh, 5.0);\n"
"  vec3 spec = u_sunCol * (D * G * F / (4.0 * ndv + 1e-3)) * sh * specK;\n"
"  vec3 diff = alb * u_sunCol * ndl * sh * mix(1.0, ao, 0.5);\n"
"  vec3 hemi = mix(u_ambG, u_ambS, N.y * 0.5 + 0.5);\n"
"  vec3 amb = alb * hemi * ao;\n"
"  vec3 R = reflect(-V, N);\n"
"  float Fe = 0.04 + 0.96 * pow(1.0 - ndv, 5.0);\n"
"  vec3 env = skyBase(R) * Fe * specK * (1.0 - rough * 0.75) * ao * 2.0;\n"
"  vec3 pl = vec3(0.0);\n"
"  if (u_plOn > 0.5) {\n"
"    vec3 Lp = u_plPos - v_wp; float dp = length(Lp); Lp /= dp;\n"
"    float q = dp / u_plRad; float att = 1.0 / (1.0 + q * q * 4.0); att *= att;\n"
"    float n = max(dot(N, Lp), 0.0);\n"
"    vec3 Hp = normalize(Lp + V); float nh = max(dot(N, Hp), 0.0);\n"
"    float sp = pow(nh, mix(220.0, 10.0, rough)) * (1.0 - rough) * specK * 2.0;\n"
"    pl = u_plCol * att * n * (alb + vec3(sp));\n"
"  }\n"
"  vec3 emis = alb * u_emis;\n"
"  vec3 col = diff + spec + amb + env + pl + emis;\n"
"  if (mat == 3) { float fg = 1.0 - exp(-dist * u_fog); col = mix(col, u_skyHor * 0.5, fg); }\n"
"  o = vec4(finish(col), 1.0);\n"
"}\n"
"";

